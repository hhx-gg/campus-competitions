const cleanName = (name: string) => name
  .replace(/^20\d{2}年?\s*/u, '')
  .replace(/（2026月历）|（2024目录）/gu, '')
  .trim()

export function competitionName(language: 'zh' | 'en', item: Competition): string {
  if (language === 'zh') return item.name
  const year = item.name.match(/^20\d{2}/u)?.[0]
  const clean = cleanName(item.name)
  const translated = names[clean] ?? 'Official competition (English title missing)'
  return year && !translated.startsWith(year) ? `${year} ${translated}` : translated
}

export function fieldValue(language: 'zh' | 'en', value: string): string {
  if (language === 'zh') return value
  if (fields[value]) return fields[value]
  if (/赛事组委会|组委会/u.test(value)) return 'Official competition committee (see source)'
  if (/本科|研究生|高职|专科|高校学生/u.test(value)) return 'Eligible college students (see official rules)'
  if (/免费/u.test(value)) return 'Free'
  if (/元|报名费|费用|标准/u.test(value)) return 'Entry fee — see official rules'
  if (/团队|个人|作品|线上|线下|校赛|省赛|决赛/u.test(value)) return 'Competition format — see official rules'
  return 'See official source'
}

export function iconCode(item: Competition): string {
  const category = fieldValue('en', item.category)
  return category.split(/\s|&/u).filter(Boolean).slice(0, 2).map((part) => part[0]).join('').toUpperCase() || 'CC'
}
